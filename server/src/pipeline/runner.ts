/** Non-retryable error codes (TRD 2.2 worker semantics). */
const NON_RETRYABLE = new Set([
  "VALIDATION_FAILED", "BUDGET_EXCEEDED", "URL_BLOCKED", "CONTENT_POLICY",
  "IDEA_TOO_LARGE", "SCHEMA_INVALID", "RUN_CANCELLED",
]);

export class CancelledError extends Error {
  constructor() {
    super("Run cancelled");
    this.name = "CancelledError";
  }
}

function backoffMs(attempt: number): number {
  const base = Math.min(60_000, 2000 * 2 ** Math.max(0, attempt - 1));
  return base * (0.5 + Math.random()); // exponential with full jitter
}

export interface RunnerDeps {
  repo: Repo;
  hub: EventHub;
  gateway: LLMGateway;
}

export class PipelineRunner {
  constructor(private deps: RunnerDeps) {}

  private async checkCancelled(run: RunRow): Promise<void> {
    if (run.cancel_requested_at) throw new CancelledError();
  }

  /** Claim + heartbeat + execute + complete/fail one stage. Never throws. */
  async runStage(orgId: string, runId: string, stage: StageName): Promise<void> {
    const { repo, hub } = this.deps;
    const owner = `worker-${process.pid}-${Math.random().toString(36).slice(2, 8)}`;
    const def = STAGE_DEFS[stage];
    const claimed = await repo.claimStage(orgId, runId, stage, owner, 90);
    if (!claimed) return;

    hub.publish(runId, "stage.status", { stage, status: "running", attempt: claimed.attempt });

    const heartbeat = setInterval(() => {
      void repo.heartbeatStage(orgId, claimed.id, owner, 90).catch(() => {});
    }, 30_000);
    heartbeat.unref?.();

    try {
      const run = await repo.getRunSystem(runId);
      if (!run) throw notFound("Run disappeared.");
      await this.checkCancelled(run);

      const emit = (event: string, data: unknown) => hub.publish(runId, event, data);
      const ctx: StageContext = { run, emit, setProgress: () => {} };

      const outcome = await this.withTimeout(this.executeStage(orgId, stage, ctx, claimed), def.timeoutMs);

      // Build immutable v1 document rows for document stages.
      const documents: { doc: DocumentRow; version: DocumentVersionRow; sections: Omit<DocumentSectionRow, "org_id" | "version_id" | "created_at" | "updated_at">[] }[] = [];
      for (const gen of outcome.documents ?? []) {
        const docId = uuidv7();
        const versionId = uuidv7();
        const fullMd = [`# ${gen.title}`, "", ...gen.sections.map((s) => `## ${s.heading}\n\n${s.body_md}\n`)].join("\n");
        const doc: DocumentRow = {
          id: docId,
          org_id: orgId,
          project_id: run.project_id,
          run_id: runId,
          template_id: null,
          doc_type: gen.doc_type,
          title: gen.title.slice(0, 200),
          current_version_id: versionId,
          latest_version_no: 1,
          created_at: nowIso(),
          updated_at: nowIso(),
          deleted_at: null,
        };
        const version: DocumentVersionRow = {
          id: versionId,
          org_id: orgId,
          document_id: docId,
          version_no: 1,
          author_type: "ai",
          author_id: run.created_by,
          change_note: `Generated by stage ${stage}`,
          content_md: fullMd,
          content_sha256: Buffer.from(fullMd).toString("hex").slice(0, 64),
          sections_count: gen.sections.length,
          model: null,
          tokens_in: 0,
          tokens_out: 0,
          created_at: nowIso(),
        };
        const sections = gen.sections.map((s, ordinal) => ({
          id: s.id,
          ordinal,
          anchor: slugify(s.heading) || `section-${ordinal}`,
          heading: s.heading,
          body_md: s.body_md,
          status: "done" as const,
          error_code: null,
        }));
        documents.push({ doc, version, sections });
      }

      const cost = STAGE_COSTS[stage];
      const tokensIn = Number(outcome.output_ref.tokens_in ?? 0);
      const tokensOut = Number(outcome.output_ref.tokens_out ?? 0);
      const ok = await repo.completeStageSucceeded(
        orgId, runId, stage, claimed.attempt,
        {
          output_ref: outcome.output_ref,
          tokens_in: tokensIn,
          tokens_out: tokensOut,
          credits_settled: cost,
          provider: String(outcome.output_ref.provider ?? "mock"),
          model: String(outcome.output_ref.model ?? "specforge-mock-1"),
        },
        {
          ledger: { amount: cost, ledger_key: `settle:${runId}:${stage}:${claimed.attempt}`, entry_type: "settle" },
          runPatch: outcome.runPatch,
          documents,
        },
      );
      if (ok) {
        hub.publish(runId, "stage.status", { stage, status: "succeeded", attempt: claimed.attempt });
        if (cost > 0) hub.publish(runId, "credit.settled", { stage, credits: cost });
      }
    } catch (err) {
      await this.handleFailure(orgId, runId, stage, claimed, err);
    } finally {
      clearInterval(heartbeat);
    }
  }

  private withTimeout<T>(p: Promise<T>, ms: number): Promise<T> {
    return new Promise<T>((resolve, reject) => {
      const timer = setTimeout(() => reject(new ApiError(503, "STAGE_TIMEOUT", `Stage exceeded its ${ms / 1000}s budget.`)), ms);
      p.then((v) => { clearTimeout(timer); resolve(v); }, (e) => { clearTimeout(timer); reject(e); });
    });
  }

  private async handleFailure(orgId: string, runId: string, stage: StageName, claimed: StageRow, err: unknown): Promise<void> {
    const { repo, hub } = this.deps;
    const def = STAGE_DEFS[stage];
    const isCancel = err instanceof CancelledError;
    const apiErr = err instanceof ApiError
      ? err
      : new ApiError(500, "STAGE_ERROR", err instanceof Error ? err.message.slice(0, 300) : "Stage failed.");

    const attempt = claimed.attempt;
    const canRetry = !isCancel && !NON_RETRYABLE.has(apiErr.code) && attempt < def.maxAttempts;
    const nextAt = canRetry ? new Date(Date.now() + backoffMs(attempt)).toISOString() : null;

    await repo.failStageAttempt(
      orgId, runId, stage, attempt,
      isCancel ? "RUN_CANCELLED" : apiErr.code,
      apiErr.message.slice(0, 500),
      nextAt,
      0, // remaining reservation is released by failRun/cancelRunNow
    );

    hub.publish(runId, "stage.status", {
      stage,
      status: isCancel ? "cancelled" : nextAt ? "retry_wait" : "failed",
      attempt,
      error_code: isCancel ? null : apiErr.code,
      error_detail: isCancel ? null : apiErr.message,
    });

    if (isCancel) {
      await this.cancelRunNow(orgId, runId);
      return;
    }
    if (!nextAt) {
      const stages = await repo.listStagesSystem(runId);
      const pending = stages.some((s) => ["queued", "retry_wait", "running"].includes(s.status));
      if (!pending) {
        await this.failRun(orgId, runId, apiErr);
      }
    }
  }

  /** Public cancel path used by the engine and the cancel route. */
  async cancelNow(orgId: string, runId: string): Promise<void> {
    return this.cancelRunNow(orgId, runId);
  }

  private async cancelRunNow(orgId: string, runId: string): Promise<void> {
    const { repo, hub } = this.deps;
    const run = await repo.getRunSystem(runId);
    if (!run || ["reviewed", "reviewed_with_warnings", "failed", "cancelled"].includes(run.status)) return;
    const stages = await repo.listStagesSystem(runId);
    for (const s of stages) {
      if (["queued", "retry_wait"].includes(s.status)) {
        await repo.failStageAttempt(orgId, runId, s.stage, s.attempt, "RUN_CANCELLED", "Cancelled by user.", null, 0);
      }
    }
    const leftover = Math.round((run.credits_reserved - run.credits_settled) * 100) / 100;
    if (leftover > 0) await repo.releaseCredits(orgId, runId, leftover, `release:${runId}:cancelled`);
    await repo.updateRunSystem(runId, {
      status: "cancelled",
      finished_at: nowIso(),
      credits_reserved: Math.max(0, run.credits_reserved - leftover),
    });
    await repo.emitOutbox([{
      id: uuidv7(),
      org_id: orgId,
      aggregate_type: "run",
      aggregate_id: runId,
      event_type: "run.cancelled",
      payload: { project_id: run.project_id },
      trace_context: null,
      available_at: nowIso(),
      created_at: nowIso(),
    }]);
    hub.publish(runId, "run.status", { status: "cancelled", progress: null });
    hub.publish(runId, "run.completed", { status: "cancelled", documents: [] });
  }

  private async failRun(orgId: string, runId: string, err: ApiError): Promise<void> {
    const { repo, hub } = this.deps;
    const run = await repo.getRunSystem(runId);
    if (!run) return;
    const leftover = Math.round((run.credits_reserved - run.credits_settled) * 100) / 100;
    if (leftover > 0) await repo.releaseCredits(orgId, runId, leftover, `release:${runId}:failed`);
    await repo.updateRunSystem(runId, {
      status: "failed",
      finished_at: nowIso(),
      error_code: err.code,
      credits_reserved: Math.max(0, run.credits_reserved - leftover),
    });
    await repo.emitOutbox([{
      id: uuidv7(),
      org_id: orgId,
      aggregate_type: "run",
      aggregate_id: runId,
      event_type: "run.failed",
      payload: { project_id: run.project_id, error_code: err.code },
      trace_context: null,
      available_at: nowIso(),
      created_at: nowIso(),
    }]);
    hub.publish(runId, "run.status", { status: "failed", progress: null });
  }

  // ===== stage implementations =====

  private async executeStage(orgId: string, stage: StageName, ctx: StageContext, claimed: StageRow): Promise<StageOutcome> {
    switch (stage) {
      case "INTAKE_VALIDATE":
        return this.stageIntake(ctx);
      case "CRAWL_FAST":
        return this.stageCrawl(ctx, claimed);
      case "EXTRACT":
        return this.stageExtract(ctx, claimed);
      case "PRD":
      case "TRD":
      case "UX":
      case "SCHEMA":
        return this.stageDocument(orgId, stage, ctx);
      case "SCHEMA_VALIDATE":
        return this.stageSchemaValidate(orgId, ctx);
      case "REVIEW":
        return this.stageReview(orgId, ctx);
      case "FINALIZE":
        return this.stageFinalize(orgId, ctx);
      default:
        throw new ApiError(500, "STAGE_ERROR", `Unknown stage ${stage}`);
    }
  }

  private async stageIntake(ctx: StageContext): Promise<StageOutcome> {
    const { scanAndRedactSecrets, detectLanguage, extractEntities } = await import("../util.js");
    const idea = (ctx.run.input.idea ?? "").trim();
    if (ctx.run.mode === "idea" && idea.length < 200) {
      throw new ApiError(400, "VALIDATION_FAILED", `The idea needs at least 200 characters (currently ${idea.length}) to produce a meaningful spec set.`);
    }
    if (idea.length > 20000) {
      throw new ApiError(413, "IDEA_TOO_LARGE", "The idea exceeds 20,000 characters. Summarise it first.");
    }
    const scanned = scanAndRedactSecrets(idea || "Reference-mode generation without idea text.");
    const language = ctx.run.language === "auto" ? detectLanguage(scanned.text) : ctx.run.language;
    const names = extractEntities(scanned.text, 6);

    if (scanned.redactions.length > 0) {
      ctx.emit("error", { code: "SECRETS_REDACTED", message: `Redacted ${scanned.redactions.length} potential secret pattern(s) before generation.` });
    }

    return {
      output_ref: { redactions: scanned.redactions, language, tokens_in: 10, tokens_out: 0, provider: "pipeline", model: "intake" },
      runPatch: {
        input: { ...ctx.run.input, redacted_idea: scanned.text, redactions: scanned.redactions },
        glossary: buildGlossary(names, ctx.run.id),
        language,
        status: "running",
        started_at: ctx.run.started_at ?? nowIso(),
      },
    };
  }

  private async stageCrawl(ctx: StageContext, claimed: StageRow): Promise<StageOutcome> {
    const { repo } = this.deps;
    if (!ctx.run.source_id) throw new ApiError(400, "VALIDATION_FAILED", "Reference run is missing its source.");
    const source = await repo.getSourceSystem(ctx.run.source_id);
    if (!source) throw new ApiError(400, "VALIDATION_FAILED", "Source not found for this run.");

    const crawl = await crawlSource(source.url, source.max_pages);
    const pages = crawl.pages.map((p) => ({ ...p, org_id: source.org_id, source_id: source.id }));
    await repo.insertCrawlPages(pages);

    const sample = pages.map((p) => p.title ?? "").join("\n");
    const status = crawl.authWall ? "auth_wall" : "preview_ready";
    await repo.updateSource(source.org_id, source.id, {
      status,
      stats: {
        captured: crawl.stats.captured,
        skipped: crawl.stats.skipped,
        duration_ms: crawl.stats.duration_ms,
        palette: crawl.palette,
        fonts: crawl.fonts,
        navigation: crawl.navigation,
        a11y: crawl.a11y,
        flows: crawl.flows,
        sample,
      },
      crawl_finished_at: nowIso(),
    });

    ctx.emit("stage.progress", { stage: "CRAWL_FAST", captured: crawl.stats.captured, skipped: crawl.stats.skipped });
    return {
      output_ref: {
        pages: pages.length, captured: crawl.stats.captured, skipped: crawl.stats.skipped,
        duration_ms: crawl.stats.duration_ms, tokens_in: 0, tokens_out: 0,
        provider: "crawler", model: "fast-crawl", attempt: claimed.attempt,
      },
    };
  }

  private async stageExtract(ctx: StageContext, claimed: StageRow): Promise<StageOutcome> {
    const { repo } = this.deps;
    if (!ctx.run.source_id) throw new ApiError(400, "VALIDATION_FAILED", "Reference run is missing its source.");
    const source = await repo.getSourceSystem(ctx.run.source_id);
    if (!source) throw new ApiError(400, "VALIDATION_FAILED", "Source not found.");
    const stats = (source.stats ?? {}) as Partial<CrawlResult> & { sample?: string };

    const crawlLike: CrawlResult = {
      pages: [],
      palette: stats.palette ?? [],
      fonts: stats.fonts ?? [],
      navigation: stats.navigation ?? [],
      flows: stats.flows ?? [],
      a11y: stats.a11y ?? { critical: 0, serious: 0, moderate: 0 },
      stats: stats.stats ?? { captured: 0, skipped: 0, duration_ms: 0 },
      authWall: false,
    };
    const { row, injectionSuspected, tokensIn } = buildExtraction(source.org_id, source.id, crawlLike, stats.sample ?? "");
    await repo.upsertDesignExtraction(row);
    return {
      output_ref: {
        components: row.components.length, flows: row.flows.length,
        injection_suspected: injectionSuspected, tokens_in: tokensIn, tokens_out: 0,
        provider: "heuristic", model: "extract-v1", attempt: claimed.attempt,
      },
      runPatch: { injection_suspected: injectionSuspected || ctx.run.injection_suspected },
    };
  }

  private async stageDocument(orgId: string, stage: StageName, ctx: StageContext): Promise<StageOutcome> {
    const { repo, gateway } = this.deps;
    await this.checkCancelled(ctx.run);
    const run = (await repo.getRunSystem(ctx.run.id)) ?? ctx.run;

    // Reference-mode grounding: load the stored extraction.
    let extraction: MockExtraction | null = null;
    if (run.source_id) {
      const source = await repo.getSourceSystem(run.source_id);
      const stats = (source?.stats ?? {}) as Partial<CrawlResult>;
      if (source) {
        extraction = {
          host: source.host,
          palette: stats.palette ?? [],
          fonts: stats.fonts ?? [],
          navigation: stats.navigation ?? [],
          a11y: stats.a11y ?? { critical: 0, serious: 0, moderate: 0 },
          flows: stats.flows ?? [],
        };
      }
    }

    const mockCtx = buildMockContext(run, extraction);
    const extractionSummary = extraction
      ? `host=${extraction.host}; palette=${extraction.palette.slice(0, 4).map((p) => p.hex).join(",")}; fonts=${extraction.fonts.map((f) => f.family).join(",")}; nav=${extraction.navigation.slice(0, 8).map((n) => n.label).join(" > ")}`
      : "";

    const generated = await gateway.generateStructured({
      run,
      stage,
      schema: DOC_OUTPUT_SCHEMA,
      mock: mockCtx,
      prompt: promptFor(stage, run, extractionSummary),
      json: true,
    });

    // Pre-generate section ids so SSE events match the persisted rows.
    const sections = generated.data.sections.map((s) => ({ id: uuidv7(), heading: s.heading, body_md: s.body_md }));

    // Stream progressively (first section within 6 s p99 per PRD FR-3).
    const docType = (stage === "UX" ? "UIUX" : stage) as "PRD" | "TRD" | "UIUX" | "SCHEMA";
    const pace = Math.max(0, env.mockSpeed);
    for (let i = 0; i < sections.length; i++) {
      await this.checkCancelled(run);
      const s = sections[i];
      const chunkSize = Math.ceil(s.body_md.length / 4);
      for (let c = 0; c < 4; c++) {
        ctx.emit("section.delta", { document: docType, section_id: s.id, ordinal: i, text: s.body_md.slice(0, chunkSize * (c + 1)) });
        if (pace > 0) await sleep(Math.min(180, 40 + s.body_md.length / 400) * pace);
      }
      ctx.emit("section.completed", { document: docType, section_id: s.id, ordinal: i, heading: s.heading, tokens: Math.ceil(s.body_md.length / 4) });
    }

    return {
      output_ref: {
        title: generated.data.title, sections: sections.length,
        tokens_in: generated.tokensIn, tokens_out: generated.tokensOut,
        provider: generated.provider, model: generated.model, calls: generated.calls,
      },
      documents: [{ doc_type: docType, title: generated.data.title, sections }],
    };
  }

  private async stageSchemaValidate(orgId: string, ctx: StageContext): Promise<StageOutcome> {
    const { repo } = this.deps;
    const docs = await repo.listDocumentsByProject(orgId, ctx.run.project_id);
    const schemaDoc = docs.find((d) => d.doc_type === "SCHEMA" && d.run_id === ctx.run.id);
    if (!schemaDoc) throw new ApiError(422, "VALIDATION_FAILED", "SCHEMA document missing before validation.");
    const version = await repo.getDocumentVersion(orgId, schemaDoc.id, "current");
    const ddl = version ? extractDdlFromSections(version.sections.map((s) => ({ heading: s.heading, body_md: s.body_md }))) : null;
    if (!ddl) throw new ApiError(422, "SCHEMA_INVALID", "No SQL DDL block found in the SCHEMA document.");

    const validation = await validateDdlText(ddl);
    if (!validation.ok) {
      throw new ApiError(422, "SCHEMA_INVALID", validation.error);
    }
    return {
      output_ref: {
        tables: validation.tables, statements: validation.statements,
        tokens_in: 0, tokens_out: 0, provider: "pipeline", model: "ddl-validator",
      },
    };
  }

  private async stageReview(orgId: string, ctx: StageContext): Promise<StageOutcome> {
    const { repo } = this.deps;
    const docs = await repo.listDocumentsByProject(orgId, ctx.run.project_id);
    const runDocs = docs.filter((d) => d.run_id === ctx.run.id);

    const glossaryIds = new Set(ctx.run.glossary.entities.map((e) => sqlIdentifier(e.name)));
    const warnings: string[] = [];

    const schemaDoc = runDocs.find((d) => d.doc_type === "SCHEMA");
    if (schemaDoc) {
      const v = await repo.getDocumentVersion(orgId, schemaDoc.id, "current");
      const ddl = v ? extractDdlFromSections(v.sections.map((s) => ({ heading: s.heading, body_md: s.body_md }))) : null;
      const parsed = new Set<string>(ddl ? [...ddl.matchAll(/CREATE TABLE\s+([a-z0-9_]+)/gi)].map((m) => m[1].toLowerCase()) : []);
      for (const expected of glossaryIds) {
        if (parsed.size > 0 && !parsed.has(expected)) warnings.push(`Schema is missing table "${expected}" from the PRD glossary.`);
      }
      for (const actual of parsed) {
        if (!glossaryIds.has(actual)) warnings.push(`Schema table "${actual}" does not appear in the PRD glossary.`);
      }
    }

    const trdDoc = runDocs.find((d) => d.doc_type === "TRD");
    if (trdDoc) {
      const v = await repo.getDocumentVersion(orgId, trdDoc.id, "current");
      const md = v?.sections.map((s) => s.body_md).join("\n") ?? "";
      const apiPaths = new Set([...md.matchAll(/`\/v1\/([a-z0-9_]+)/g)].map((m) => m[1].toLowerCase()));
      const missing = [...glossaryIds].filter((g) => !apiPaths.has(g));
      if (apiPaths.size > 0 && missing.length > 0) {
        warnings.push(`TRD API contract does not cover: ${missing.join(", ")}.`);
      }
    }

    const uxDoc = runDocs.find((d) => d.doc_type === "UIUX");
    if (uxDoc) {
      const v = await repo.getDocumentVersion(orgId, uxDoc.id, "current");
      const md = v?.sections.map((s) => s.body_md).join("\n") ?? "";
      const bindings = new Set<string>();
      const bindingLine = /Data bindings?:([^\n]*)/i.exec(md);
      if (bindingLine) {
        for (const m of bindingLine[1].matchAll(/`([a-z0-9_]+)`/g)) bindings.add(m[1].toLowerCase());
      } else {
        for (const m of md.matchAll(/`([a-z0-9_]+)`/g)) bindings.add(m[1].toLowerCase());
      }
      const missing = [...glossaryIds].filter((g) => !bindings.has(g));
      if (bindings.size > 0 && missing.length > 0) {
        warnings.push(`UX specification does not bind: ${missing.join(", ")}.`);
      }
    }

    if (ctx.run.injection_suspected) {
      warnings.push("Prompt-injection patterns were detected in crawled content; generation used sanitized data only.");
    }

    return {
      output_ref: { warnings, checked: glossaryIds.size, tokens_in: 0, tokens_out: 0, provider: "pipeline", model: "consistency-review" },
      warnings,
    };
  }

  private async stageFinalize(orgId: string, ctx: StageContext): Promise<StageOutcome> {
    const { repo, hub } = this.deps;
    const docs = await repo.listDocumentsByProject(orgId, ctx.run.project_id);
    const runDocs = docs.filter((d) => d.run_id === ctx.run.id);

    // Warnings come from the REVIEW stage output (deterministic entity diff).
    const stages = await repo.listStagesSystem(ctx.run.id);
    const reviewStage = stages.find((s) => s.stage === "REVIEW");
    const warnings = Array.isArray((reviewStage?.output_ref as { warnings?: string[] } | undefined)?.warnings)
      ? ((reviewStage?.output_ref as { warnings: string[] }).warnings)
      : [];
    const finalStatus = warnings.length > 0 ? "reviewed_with_warnings" : "reviewed";

    const leftover = Math.round((ctx.run.credits_reserved - ctx.run.credits_settled) * 100) / 100;
    if (leftover > 0) {
      await repo.releaseCredits(orgId, ctx.run.id, leftover, `release:${ctx.run.id}:finalize`);
    }

    await repo.emitOutbox([{
      id: uuidv7(),
      org_id: orgId,
      aggregate_type: "run",
      aggregate_id: ctx.run.id,
      event_type: "run.completed",
      payload: { project_id: ctx.run.project_id, status: finalStatus, documents: runDocs.map((d) => d.id) },
      trace_context: null,
      available_at: nowIso(),
      created_at: nowIso(),
    }]);

    hub.publish(ctx.run.id, "run.status", { status: finalStatus, progress: 1 });
    hub.publish(ctx.run.id, "run.completed", {
      status: finalStatus,
      documents: runDocs.map((d) => ({ id: d.id, doc_type: d.doc_type, title: d.title })),
      warnings,
    });

    return {
      output_ref: { status: finalStatus, warnings, tokens_in: 0, tokens_out: 0, provider: "pipeline", model: "finalize" },
      runPatch: {
        status: finalStatus,
        finished_at: nowIso(),
        credits_reserved: Math.max(0, ctx.run.credits_reserved - leftover),
      },
    };
  }
}

function buildGlossary(names: string[], runId: string): RunRow["glossary"] {
  const canonical: Record<string, string> = {};
  const entities = names.map((name) => {
    const definition =
      `A tenant-scoped ${name.toLowerCase()} record owned by an organization, with UUIDv7 identity, audit timestamps and soft delete. Seeded from intake by run ${runId.slice(0, 8)}.`;
    canonical[name] = definition;
    return { name, definition };
  });
  return { canonical, entities };
}

/** Text-mode DDL validation used in both repo modes (PG additionally re-executes in CI). */
export async function validateDdlText(ddl: string): Promise<
  | { ok: true; tables: string[]; statements: number }
  | { ok: false; error: string }
> {
  const clean = ddl.replace(/--[^\n]*/g, "").trim();
  if (clean.length === 0) return { ok: false, error: "DDL is empty." };
  let depth = 0;
  for (const ch of clean) {
    if (ch === "(") depth += 1;
    if (ch === ")") depth -= 1;
    if (depth < 0) return { ok: false, error: "Unbalanced parentheses in DDL." };
  }
  if (depth !== 0) return { ok: false, error: "Unbalanced parentheses in DDL." };

  const statements = clean.split(";").map((s) => s.trim()).filter(Boolean);
  if (statements.length === 0) return { ok: false, error: "No statements found." };

  const createTables = [...clean.matchAll(/CREATE TABLE\s+([a-zA-Z0-9_]+)/gi)].map((m) => m[1].toLowerCase());
  if (createTables.length === 0) return { ok: false, error: "DDL contains no CREATE TABLE statements." };

  const known = new Set([...createTables, "organizations", "users", "projects"]);
  const fkRe = /REFERENCES\s+([a-zA-Z0-9_]+)/gi;
  let m: RegExpExecArray | null;
  while ((m = fkRe.exec(clean)) !== null) {
    if (!known.has(m[1].toLowerCase())) {
      return { ok: false, error: `FOREIGN KEY references unknown table "${m[1]}".` };
    }
  }
  return { ok: true, tables: createTables, statements: statements.length };
}
