/** Export routes: single-document export (sync) and full-run bundle (202 + poll). */
import type { FastifyInstance } from "fastify";
import { mkdir, writeFile, readFile, stat } from "node:fs/promises";
import { dirname, join } from "node:path";
import { repo } from "../db/repo-holder.js";
import { createExportSchema, createBundleSchema } from "../schemas.js";
import { parseBody, requireAuth, requireRole } from "./helpers.js";
import { notFound, unprocessable } from "../errors.js";
import { env } from "../env.js";
import { markdownToDocxBlob } from "../exports/docx.js";
import { sectionsToMarkdown } from "../exports/markdown.js";
import { buildFullRunBundle } from "../exports/bundle.js";
import { writeAudit, auditEntry } from "../services/audit.js";
import { uuidv7, nowIso } from "../util.js";

const MIME: Record<string, string> = {
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  md: "text/markdown; charset=utf-8",
  zip: "application/zip",
  pdf: "application/pdf",
};

export function registerExportRoutes(app: FastifyInstance): void {
  app.post("/v1/documents/:id/exports", async (request, reply) => {
    const auth = await requireAuth(request);
    requireRole(auth, "viewer");
    const { id } = request.params as { id: string };
    const body = parseBody(createExportSchema, request.body);
    const document = await repo.getDocument(auth.orgId, id);
    if (!document) throw notFound("Document not found.");
    const current = await repo.getDocumentVersion(auth.orgId, id, "current");
    if (!current) throw notFound("Document has no versions.");

    const exportId = uuidv7();
    const ext = body.format === "md" ? "md" : body.format === "docx" ? "docx" : "pdf";
    const dir = join(env.dataDir, "exports");
    const filePath = join(dir, `${exportId}.${ext}`);
    await mkdir(dir, { recursive: true });

    if (body.format === "docx") {
      const md = sectionsToMarkdown(current.version.content_md.split("\n\n## ").length > 1 ? current.version.content_md : current.version.content_md, current.sections);
      const buf = await markdownToDocxBlob(md, document.title, `Generated by SpecForge · ${document.doc_type}`);
      await writeFile(filePath, buf);
    } else {
      const md = sectionsToMarkdown(document.title, current.sections);
      await writeFile(filePath, md, "utf8");
    }
    const size = await stat(filePath);

    const row = await repo.insertExport({
      id: exportId,
      org_id: auth.orgId,
      document_id: id,
      run_id: null,
      requested_by: auth.userId,
      format: body.format,
      status: "ready",
      s3_key: filePath,
      size_bytes: size.size,
      error_code: null,
      expires_at: new Date(Date.now() + 24 * 3600 * 1000).toISOString(),
      created_at: nowIso(),
      updated_at: nowIso(),
    });
    await writeAudit(repo, [
      auditEntry({
        org_id: auth.orgId,
        actor_user_id: auth.userId,
        actor_type: auth.via === "api_key" ? "api_key" : "user",
        action: "export.created",
        resource_type: "export",
        resource_id: exportId,
        metadata: { format: body.format, document_id: id },
      }),
    ]);
    reply.code(202).send({ id: row.id, status: row.status, format: row.format, download: `/v1/exports/${row.id}` });
  });

  app.post("/v1/runs/:id/bundle", async (request, reply) => {
    const auth = await requireAuth(request);
    requireRole(auth, "viewer");
    const { id } = request.params as { id: string };
    const body = parseBody(createBundleSchema, request.body);
    const run = await repo.getRun(auth.orgId, id);
    if (!run) throw notFound("Run not found.");
    if (!["reviewed", "reviewed_with_warnings"].includes(run.status)) {
      throw unprocessable("RUN_NOT_FINISHED", `Bundle export requires a finished run (current: ${run.status}).`);
    }

    const exportId = uuidv7();
    await repo.insertExport({
      id: exportId,
      org_id: auth.orgId,
      document_id: null,
      run_id: id,
      requested_by: auth.userId,
      format: "zip",
      status: "running",
      s3_key: null,
      size_bytes: null,
      error_code: null,
      expires_at: new Date(Date.now() + 24 * 3600 * 1000).toISOString(),
      created_at: nowIso(),
      updated_at: nowIso(),
    });

    try {
      const allDocs = await repo.listDocumentsByProject(auth.orgId, run.project_id);
      const bundleDocs = [];
      for (const doc of allDocs.filter((d) => d.run_id === id)) {
        const ver = await repo.getDocumentVersion(auth.orgId, doc.id, "current");
        if (ver) {
          bundleDocs.push({
            doc_type: doc.doc_type,
            title: doc.title,
            sections: ver.sections.map((s) => ({ heading: s.heading, body_md: s.body_md })),
          });
        }
      }
      const zip = await buildFullRunBundle(id, bundleDocs, { formats: body.formats, watermark: true });
      const dir = join(env.dataDir, "exports");
      const filePath = join(dir, `${exportId}.zip`);
      await mkdir(dir, { recursive: true });
      await writeFile(filePath, zip);
      await repo.updateExport(auth.orgId, exportId, { status: "ready", s3_key: filePath, size_bytes: zip.length });
    } catch (err) {
      await repo.updateExport(auth.orgId, exportId, { status: "failed", error_code: "BUNDLE_FAILED" });
      throw err;
    }

    reply.code(202).send({ id: exportId, status: "ready", format: "zip", download: `/v1/exports/${exportId}` });
  });

  app.get("/v1/exports/:id", async (request, reply) => {
    const auth = await requireAuth(request);
    const { id } = request.params as { id: string };
    const row = await repo.getExport(auth.orgId, id);
    if (!row) throw notFound("Export not found.");
    if (row.status !== "ready" || !row.s3_key) {
      throw unprocessable("EXPORT_NOT_READY", `Export is ${row.status}.`);
    }
    if (row.expires_at && new Date(row.expires_at).getTime() < Date.now()) {
      throw unprocessable("EXPORT_EXPIRED", "This export has expired; request a new one.");
    }
    try {
      const buf = await readFile(row.s3_key);
      reply
        .code(200)
        .header("content-type", MIME[row.format] ?? "application/octet-stream")
        .header("content-disposition", `attachment; filename="specforge-export-${row.id}.${row.format}"`)
        .header("content-length", String(buf.length))
        .send(buf);
    } catch {
      throw notFound("Export file is no longer available.");
    }
  });
}
